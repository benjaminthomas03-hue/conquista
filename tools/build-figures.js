// Renders the army figure sprites into public/figures (3 kinds x 6 player colours) plus meta.js with their sizes.
// Run: node tools/build-figures.js   (needs Playwright's Chromium and the 'three' dev dependency)
const fs = require('fs');
const path = require('path');
const { chromium } = require('playwright');
const COLORS = ['#d64545', '#3b7ddd', '#2e9e62', '#e2b42d', '#8f5bd0', '#e8792b']; // keep in sync with server/index.js
(async () => {
  const b = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--allow-file-access-from-files'] });
  const p = await b.newPage();
  p.on('pageerror', (e) => { console.error(e); process.exitCode = 1; });
  await p.goto('file://' + path.join(__dirname, 'figures', 'figures.html'));
  await p.waitForTimeout(300);
  const out = await p.evaluate((c) => window.renderAll(c), COLORS);
  const dir = path.join(__dirname, '..', 'public', 'figures');
  fs.mkdirSync(dir, { recursive: true });
  const meta = {};
  let bytes = 0;
  for (const [k, v] of Object.entries(out)) {
    const buf = Buffer.from(v.url.split(',')[1], 'base64');
    fs.writeFileSync(path.join(dir, k + '.png'), buf);
    meta[k] = [v.w, v.h]; bytes += buf.length;
  }
  fs.writeFileSync(path.join(dir, 'meta.js'), '// Generated by tools/build-figures.js\nwindow.CONQUISTA_FIGURES = ' + JSON.stringify(meta) + ';\n');
  console.log(`Wrote ${Object.keys(out).length} figure sprites (${Math.round(bytes / 1024)} KB)`);
  await b.close();
})();
